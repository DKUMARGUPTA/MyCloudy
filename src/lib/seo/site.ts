/**
 * SEO site constants (P7-SEO) — the single source of truth for canonical
 * URLs, brand naming and social-card assets. Every metadata builder in
 * src/lib/seo/* derives from these values, so a future domain change is
 * a one-line edit.
 */

export const SITE = {
  /**
   * Canonical production origin (user-attached Vercel domain).
   * WWW host: the apex docopdf.com 308-redirects to www on Vercel, so every
   * canonical/og:url/sitemap/robots reference must use www (one host site-wide
   * — Google Search Console property, hreflang and social previews included).
   */
  url: "https://www.docopdf.com",
  name: "DocoPDF",
  /** Appended to every page title by the metadata builders. */
  titleSuffix: " | DocoPDF",
  tagline: "100 free online PDF tools",
  /** 1200×630 social card (generated by scripts/gen-og-image.ts). */
  ogImage: "/og-image.png",
  /** Twitter handle — update when the account exists. */
  twitterSite: "@docopdf",
  localeTags: { en: "en_US", hi: "hi_IN" } as const,
  /** Static content pages (about | contact | privacy | terms). */
  staticPages: ["about", "contact", "privacy", "terms"] as const,
} as const;

export type StaticPageId = (typeof SITE.staticPages)[number];

/** Absolute URL for a site path (no trailing-slash games). */
export function absoluteUrl(path: string): string {
  return `${SITE.url}${path.startsWith("/") ? path : `/${path}`}`;
}

/** Hindi mirror path for a canonical English path ("/tool/x" → "/hi/tool/x"). */
export function hindiPath(path: string): string {
  if (path === "/" || path === "") return "/hi";
  return `/hi${path.startsWith("/") ? path : `/${path}`}`;
}
