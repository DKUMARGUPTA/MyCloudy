def merge(path, wm, tool_extra):
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    data.setdefault("wm", {}).update(wm)
    data.setdefault("tool", {}).update(tool_extra)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(data, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print(f"{path}: wm keys={len(data['wm'])}, tool keys={len(data['tool'])}")


merge("src/i18n/en.json", EN_WM, EN_TOOL)
merge("src/i18n/hi.json", HI_WM, HI_TOOL)
